// Generates the stained-glass decoration (Art Nouveau window style, Georgia fall leaves):
//   public/stained-glass-panel.svg  - side window art for wide screens (pale glass + branch)
//   public/stained-glass-frame.svg  - leaded came frame, used as a CSS border-image
//   public/stained-glass-came.svg   - horizontal came strip tile (top of page on phones)
//   public/stained-glass-sprig.svg  - transom centerpiece above the footer on phones
// Compositions are placed by hand (see PANEL_LEAVES / SPRIG_LEAVES), not scattered.
// Re-run after tweaking: node scripts/stained-glass.mjs
import { writeFileSync } from 'node:fs'

const out = (name, svg) => writeFileSync(new URL(`../public/${name}`, import.meta.url), svg)
const NOTE = '<!-- Generated by scripts/stained-glass.mjs. Edit the script, not this file. -->'

// ---------- palette ----------
const LEAD = '#5b3d2e' // came / lead lines: deep copper-brown
const PANE = '#b39278' // lighter lead dividing the background glass
const GLASS_BG = '#f1e7d3' // pale cathedral glass behind the branch
const STEM = '#8a6a3e'
const ROSE = '#c08a73' // rose gold / copper frame glass
const AMBER = '#d4a35e'
const CORNER = '#9e4426'
const LEAF = {
  rust: ['#dc8e63', '#a8492a'],
  amber: ['#efcb86', '#c98b3e'],
  sage: ['#b6c0a0', '#6f7f5f'],
  gold: ['#d3c493', '#8f7f4f'],
}

const f = (n) => +n.toFixed(2)

function gradients() {
  return Object.entries(LEAF)
    .map(([k, [light, dark]]) => {
      const mid = mix(light, dark, 0.5)
      return `<linearGradient id="${k}L" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="${light}"/><stop offset="1" stop-color="${mid}"/></linearGradient>` +
        `<linearGradient id="${k}R" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="${mid}"/><stop offset="1" stop-color="${dark}"/></linearGradient>`
    })
    .join('')
}

function mix(a, b, t) {
  const p = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16))
  const [x, y] = [p(a), p(b)]
  return '#' + x.map((v, i) => Math.round(v + (y[i] - v) * t).toString(16).padStart(2, '0')).join('')
}

// ---------- leaf shapes: right half outline, base (0,0) to tip (0,-100) ----------
function catmull(points) {
  let d = ''
  for (let i = 0; i < points.length - 1; i++) {
    const p0 = points[i - 1] || points[i], p1 = points[i], p2 = points[i + 1], p3 = points[i + 2] || p2
    const c1 = [p1[0] + (p2[0] - p0[0]) / 6, p1[1] + (p2[1] - p0[1]) / 6]
    const c2 = [p2[0] - (p3[0] - p1[0]) / 6, p2[1] - (p3[1] - p1[1]) / 6]
    d += ` C${f(c1[0])},${f(c1[1])} ${f(c2[0])},${f(c2[1])} ${f(p2[0])},${f(p2[1])}`
  }
  return d
}
const lines = (pts) => pts.slice(1).map(([x, y]) => ` L${x},${y}`).join('')

function sweetgumHalf() {
  // five-pointed star leaf: tips at 0/72/144 deg from up, notches between
  const C = [0, -48], R = 52, r = 20
  const at = (deg, rad) => [f(C[0] + rad * Math.sin((deg * Math.PI) / 180)), f(C[1] - rad * Math.cos((deg * Math.PI) / 180))]
  return [[0, 0], at(165, r * 1.1), at(140, R * 0.95), at(108, r), at(72, R), at(36, r), [0, -100]]
}

const SHAPES = {
  maple: {
    half: [[0, 0], [5, -6], [8, -14], [28, -8], [23, -22], [36, -27], [58, -22], [49, -37], [63, -52], [45, -53], [41, -63], [31, -59], [33, -74], [19, -71], [16, -85], [8, -81], [0, -100]],
    smooth: false,
    veins: [[0, -14, 55, -23], [0, -16, 58, -50], [0, -30, 29, -70]],
  },
  sweetgum: {
    half: sweetgumHalf(),
    smooth: false,
    veins: [[0, -40, 46, -63], [0, -34, 28, -13]],
  },
  oak: {
    half: [[0, 0], [6, -6], [8, -14], [21, -16], [24, -25], [15, -31], [29, -37], [30, -47], [18, -51], [27, -59], [26, -69], [15, -71], [18, -81], [11, -91], [0, -100]],
    smooth: true,
    veins: [[0, -22, 20, -26], [0, -40, 25, -42], [0, -60, 22, -64], [0, -78, 14, -82]],
  },
  elm: {
    half: [[0, 0], [11, -7], [21, -19], [27, -35], [28, -51], [24, -67], [16, -83], [8, -93], [0, -100]],
    smooth: true,
    veins: [[0, -26, 20, -38], [0, -46, 24, -58], [0, -66, 17, -78]],
  },
}

function leaf({ type, x, y, rot, size, color }) {
  const s = SHAPES[type]
  const k = size / 100
  const sw = (w) => f(w / k) // keep stroke widths constant after scaling
  const half = 'M0,0' + (s.smooth ? catmull(s.half) : lines(s.half))
  const piece = `${half} Z`
  const veins = s.veins
    .flatMap(([x1, y1, x2, y2]) => [`M${x1},${y1} L${x2},${y2}`, `M${-x1},${y1} L${-x2},${y2}`])
    .join(' ')
  return `<g transform="translate(${x},${y}) rotate(${rot}) scale(${k})">
<path d="${piece}" transform="scale(-1,1)" fill="url(#${color}L)"/>
<path d="${piece}" fill="url(#${color}R)"/>
<path d="${veins}" fill="none" stroke="${LEAD}" stroke-opacity="0.45" stroke-width="${sw(0.9)}" stroke-linecap="round"/>
<path d="M0,6 L0,-96" fill="none" stroke="${LEAD}" stroke-width="${sw(1.6)}" stroke-linecap="round"/>
<path d="${half}" fill="none" stroke="${LEAD}" stroke-width="${sw(2.4)}" stroke-linejoin="round"/>
<path d="${half}" transform="scale(-1,1)" fill="none" stroke="${LEAD}" stroke-width="${sw(2.4)}" stroke-linejoin="round"/>
</g>`
}

function stem(d, w = 7) {
  return `<path d="${d}" fill="none" stroke="${LEAD}" stroke-width="${w}" stroke-linecap="round"/>` +
    `<path d="${d}" fill="none" stroke="${STEM}" stroke-width="${w - 3.4}" stroke-linecap="round"/>`
}

function tendril(cx, cy, r0, turns, start, dir = 1) {
  const pts = []
  const n = 60
  for (let i = 0; i <= n; i++) {
    const t = i / n
    const a = start + dir * t * turns * 2 * Math.PI
    const r = r0 * (1 - 0.85 * t)
    pts.push([cx + r * Math.cos(a), cy + r * Math.sin(a)])
  }
  const d = 'M' + pts.map(([x, y]) => `${f(x)},${f(y)}`).join(' L')
  return `<path d="${d}" fill="none" stroke="${LEAD}" stroke-width="2.2" stroke-linecap="round"/>`
}

// ---------- 1) side window panel (wide screens) ----------
// One long, gentle S-curve stem (two cubic segments). Side branches leave the stem and
// each ends in a leaf, so every leaf is attached. A couple of leaves sit on the stem itself.
const PW = 200, PH = 1400
const STEM_SEGS = [
  [[104, 1420], [168, 1150], [44, 960], [100, 720]],
  [[100, 720], [150, 500], [52, 260], [100, -20]],
]
const bez = ([a, b, c, d], t) => [0, 1].map((i) => (1 - t) ** 3 * a[i] + 3 * (1 - t) ** 2 * t * b[i] + 3 * (1 - t) * t ** 2 * c[i] + t ** 3 * d[i])
function stemAt(y) {
  // x of the stem at height y (sampled)
  let best = [0, Infinity]
  for (const s of STEM_SEGS) for (let t = 0; t <= 1; t += 0.002) {
    const [x, yy] = bez(s, t)
    if (Math.abs(yy - y) < best[1]) best = [x, Math.abs(yy - y)]
  }
  return best[0]
}
const stemD = `M${STEM_SEGS[0][0]}` + STEM_SEGS.map(([, b, c, d]) => ` C${b} ${c} ${d}`).join('')

// background glass panes: a few gently curved lead lines, like cut cathedral glass
const panes = [
  'M0,170 C60,156 140,186 200,166', 'M0,400 C70,420 130,386 200,410', 'M0,640 C60,624 150,654 200,632',
  'M0,880 C80,898 120,864 200,886', 'M0,1110 C60,1094 140,1126 200,1104', 'M0,1310 C70,1328 130,1296 200,1318',
  'M46,0 C40,360 56,900 44,1400', 'M158,0 C164,420 150,980 160,1400',
]

// branches: [y on stem, side (-1 left / 1 right), reach, rise, leaf]
const BRANCHES = [
  [1290, 1, 44, 40, { type: 'oak', size: 88, color: 'rust' }],
  [1150, -1, 42, 46, { type: 'maple', size: 92, color: 'amber' }],
  [990, 1, 40, 44, { type: 'elm', size: 80, color: 'sage' }],
  [840, -1, 44, 40, { type: 'sweetgum', size: 90, color: 'rust' }],
  [640, 1, 42, 48, { type: 'maple', size: 94, color: 'rust' }],
  [500, -1, 40, 44, { type: 'oak', size: 86, color: 'gold' }],
  [340, 1, 42, 40, { type: 'sweetgum', size: 88, color: 'amber' }],
  [190, -1, 38, 44, { type: 'elm', size: 78, color: 'rust' }],
]
let branchSvg = ''
const panelLeaves = []
for (const [y, side, reach, rise, lf] of BRANCHES) {
  const x0 = stemAt(y)
  const x1 = x0 + side * reach, y1 = y - rise
  branchSvg += stem(`M${f(x0)},${y} C${f(x0 + side * reach * 0.5)},${y - 4} ${f(x1 - side * 6)},${y1 + rise * 0.4} ${f(x1)},${f(y1)}`, 5)
  const angle = (Math.atan2(y1 - y, x1 - x0) * 180) / Math.PI + 90 // leaf continues the branch direction
  panelLeaves.push({ ...lf, x: f(x1), y: f(y1), rot: f(angle * 0.85) })
}
// two leaves riding the stem near the top and bottom, pointing up
panelLeaves.push({ type: 'maple', x: f(stemAt(70)), y: 70, rot: 6, size: 84, color: 'sage' })
panelLeaves.push({ type: 'elm', x: f(stemAt(1380)), y: 1380, rot: -10, size: 70, color: 'amber' })

const panel = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${PW} ${PH}" width="${PW}" height="${PH}">
${NOTE}
<defs>${gradients()}</defs>
<rect width="${PW}" height="${PH}" fill="${GLASS_BG}"/>
${panes.map((d) => `<path d="${d}" fill="none" stroke="${PANE}" stroke-width="1.6"/>`).join('\n')}
${stem(stemD, 8)}
${branchSvg}
${tendril(stemAt(1060) + 30, 1050, 15, 1.4, 3.6, 1)}${tendril(stemAt(560) - 30, 560, 14, 1.3, 0.2, -1)}${tendril(stemAt(260) + 28, 258, 13, 1.3, 3.4, 1)}
${panelLeaves.map(leaf).join('\n')}
</svg>
`
out('stained-glass-panel.svg', panel)

// ---------- 2) came frame for CSS border-image (slice 12, edges 36 long) ----------
const B = 12, FS = 60
function seg(x, y, w, h, fill) {
  return `<rect x="${x}" y="${y}" width="${w}" height="${h}" fill="${fill}" stroke="${LEAD}" stroke-width="1.6"/>`
}
const frame = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${FS} ${FS}" width="${FS}" height="${FS}">
${NOTE}
${[[0, 0], [FS - B, 0], [0, FS - B], [FS - B, FS - B]].map(([x, y]) => seg(x + 0.8, y + 0.8, B - 1.6, B - 1.6, CORNER)).join('')}
${seg(B, 0.8, 18, B - 1.6, ROSE)}${seg(B + 18, 0.8, 18, B - 1.6, AMBER)}
${seg(B, FS - B + 0.8, 18, B - 1.6, AMBER)}${seg(B + 18, FS - B + 0.8, 18, B - 1.6, ROSE)}
${seg(0.8, B, B - 1.6, 18, AMBER)}${seg(0.8, B + 18, B - 1.6, 18, ROSE)}
${seg(FS - B + 0.8, B, B - 1.6, 18, ROSE)}${seg(FS - B + 0.8, B + 18, B - 1.6, 18, AMBER)}
</svg>
`
out('stained-glass-frame.svg', frame)

// ---------- 3) horizontal came strip tile (repeat-x) ----------
const came = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 56 12" width="56" height="12">
${NOTE}
${seg(0.8, 0.8, 26.4, 10.4, ROSE)}${seg(28.8, 0.8, 26.4, 10.4, AMBER)}
</svg>
`
out('stained-glass-came.svg', came)

// ---------- 4) transom sprig (phones, above the footer) ----------
const SW = 320, SH = 50
const SPRIG_LEAVES = [
  { type: 'oak', x: 112, y: 32, rot: -62, size: 32, color: 'gold' },
  { type: 'sweetgum', x: 210, y: 31, rot: 60, size: 34, color: 'amber' },
  { type: 'maple', x: 160, y: 42, rot: 0, size: 34, color: 'rust' },
]
const sprig = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${SW} ${SH}" width="${SW}" height="${SH}">
${NOTE}
<defs>${gradients()}</defs>
${stem('M70,40 C110,24 130,46 160,40 C190,34 212,24 250,40', 5.4)}
${tendril(78, 28, 9, 1.3, 1.2, -1)}${tendril(242, 28, 9, 1.3, 1.9, 1)}
${SPRIG_LEAVES.map(leaf).join('\n')}
</svg>
`
out('stained-glass-sprig.svg', sprig)

