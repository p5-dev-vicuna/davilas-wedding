// Generates public/stained-glass-vine.svg: a vertically tiling stained-glass vine with
// leaves split into panes, for the decorative side borders on wide screens.
// Re-run after tweaking: node scripts/stained-glass.mjs
import { writeFileSync } from 'node:fs'

const W = 200 // tile width
const H = 720 // tile height (tiles seamlessly top to bottom)
const CX = W / 2
const AMP = 14 // vine sway

// Palette: fall glass in the site's family. Lead lines are rose gold.
const LEAD = '#b9806f'
const GLASS = ['#d9a55b', '#b5562f', '#8a9a7b', '#a89968', '#c97b45', '#6f7f62']

// deterministic pseudo-random so the file is stable between runs
let seed = 23
const rand = () => ((seed = (seed * 16807) % 2147483647) / 2147483647)

const vineX = (y) => CX + AMP * Math.sin((2 * Math.PI * y) / H)
const vineSlope = (y) => ((AMP * 2 * Math.PI) / H) * Math.cos((2 * Math.PI * y) / H)
const f = (n) => n.toFixed(1)

// vine path, sampled so it lines up exactly at y=0 and y=H
let vine = `M${f(vineX(0))},0`
for (let y = 8; y <= H; y += 8) vine += ` L${f(vineX(y))},${f(y)}`

// One leaf: local x runs base->tip along the midrib, y is across the leaf.
function leaf(bx, by, angle, len, wid, lobes) {
  const cos = Math.cos(angle), sin = Math.sin(angle)
  const P = (x, y) => [bx + x * cos - y * sin, by + x * sin + y * cos]
  const half = (t) => wid * Math.pow(Math.sin(Math.PI * t), 0.85) * (1 + 0.12 * Math.sin(t * Math.PI * lobes))
  const edge = (t, side) => P(t * len, side * half(t))
  const mid = (t) => P(t * len, 0)

  const veins = [0, 0.26, 0.48, 0.7, 1]
  const slant = 0.1
  const panes = []
  for (const side of [1, -1]) {
    for (let i = 0; i < veins.length - 1; i++) {
      const a = veins[i], b = veins[i + 1]
      const ea = Math.min(a === 0 ? 0 : a + slant, 1)
      const eb = Math.min(b === 1 ? 1 : b + slant, 1)
      const pts = [mid(a), mid(b)]
      for (let k = 0; k <= 6; k++) pts.push(edge(eb - ((eb - ea) * k) / 6, side))
      panes.push(pts)
    }
  }
  const outline = []
  for (let k = 0; k <= 24; k++) outline.push(edge(k / 24, 1))
  for (let k = 24; k >= 0; k--) outline.push(edge(k / 24, -1))

  const poly = (pts) => pts.map(([x, y]) => `${f(x)},${f(y)}`).join(' ')
  let s = ''
  for (const p of panes) {
    const c = GLASS[Math.floor(rand() * GLASS.length)]
    s += `<polygon points="${poly(p)}" fill="${c}" fill-opacity="${(0.58 + rand() * 0.2).toFixed(2)}" stroke="${LEAD}" stroke-width="1.3" stroke-linejoin="round"/>`
  }
  s += `<polygon points="${poly(outline)}" fill="none" stroke="${LEAD}" stroke-width="2.6" stroke-linejoin="round"/>`
  return s
}

let leaves = ''
let berries = ''
const ys = [70, 170, 260, 370, 460, 560, 650]
ys.forEach((y, i) => {
  const side = i % 2 === 0 ? 1 : -1
  const x = vineX(y)
  const tilt = Math.atan(vineSlope(y))
  // leaves angle outward and slightly upward, alternating sides
  const angle = side === 1 ? -0.55 + tilt * 0.3 : Math.PI + 0.55 + tilt * 0.3
  const len = 72 + rand() * 12
  const wid = 22 + rand() * 5
  // short stem from vine to leaf base
  const sx = x + side * 8, sy = y - 6
  leaves += `<path d="M${f(x)},${f(y)} Q${f(x + side * 4)},${f(y - 6)} ${f(sx)},${f(sy)}" fill="none" stroke="${LEAD}" stroke-width="1.6"/>`
  leaves += leaf(sx, sy, angle, len, wid, 3)
  // a small cluster of glass berries opposite every other leaf
  if (i % 2 === 1) {
    for (let k = 0; k < 3; k++) {
      const bxp = x - side * (12 + k * 7), byp = y + 14 + (k % 2) * 8
      berries += `<circle cx="${f(bxp)}" cy="${f(byp)}" r="4.2" fill="${GLASS[1]}" fill-opacity="0.55" stroke="${LEAD}" stroke-width="1.2"/>`
    }
  }
})

const art = `<path d="${vine}" fill="none" stroke="${LEAD}" stroke-width="3" stroke-linecap="round"/>
${leaves}
${berries}`
const note = '<!-- Generated by scripts/stained-glass.mjs. Edit the script, not this file. -->'

// Vertical tile: side borders on wide screens (repeats top to bottom).
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W}" height="${H}">
${note}
${art}
</svg>
`
writeFileSync(new URL('../public/stained-glass-vine.svg', import.meta.url), svg)

// Horizontal tile: the same vine turned sideways, a garland band for phones/tablets
// (repeats left to right). rotate(-90) then shift maps (x, y) -> (y, W - x).
const svgH = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${H} ${W}" width="${H}" height="${W}">
${note}
<g transform="translate(0,${W}) rotate(-90)">
${art}
</g>
</svg>
`
writeFileSync(new URL('../public/stained-glass-garland.svg', import.meta.url), svgH)
console.log('wrote public/stained-glass-vine.svg and public/stained-glass-garland.svg')
